"""Async Kafka consumer for SIEM telemetry ingestion.

This worker listens on the `spyderxdr.telemetry` topic, feeds raw telemetry
through the detection engine, and updates agent tracking — WITHOUT persisting
raw events to the relational database. Raw event storage is handled exclusively
by Elasticsearch via the Fluentd/Kafka-to-ES stream.
"""

import asyncio
import json
import logging
import os
from datetime import datetime

from aiokafka import AIOKafkaConsumer
from sqlalchemy import select, delete

from app.models.database import Agent
from app.services.database import Database
from app.detection.engine import DetectionEngine
from app.services.redis_service import RedisService

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(name)s - %(levelname)s - %(message)s')
logger = logging.getLogger("kafka_consumer")

BROKER = os.getenv("KAFKA_BROKER", "localhost:9092")
TOPIC = os.getenv("KAFKA_TOPIC", "spyderxdr.telemetry")


def _coerce_timestamp(value):
    if isinstance(value, datetime):
        return value
    if not value:
        return datetime.utcnow()
    try:
        return datetime.fromisoformat(str(value))
    except Exception:
        return datetime.utcnow()


async def _process_kafka_message(db: Database, payload: dict, detection_engine: DetectionEngine) -> None:
    """Process a single Kafka telemetry message.

    - Updates the Agent record (upsert-based tracking with events_processed counter).
    - Passes the event through the DetectionEngine in-memory.
    - Does NOT write raw Event rows to the relational database — those live in Elasticsearch.
    - The commit persists Agent changes and any Alert / Ticket / Response the detection engine creates.
    """
    event_timestamp = _coerce_timestamp(payload.get("timestamp"))
    hostname = str(payload.get("hostname") or "localhost")
    source_ip = str(payload.get("source_ip") or "127.0.0.1")
    agent_id = str(payload.get("agent_id") or "kafka-consumer")
    event_type = str(payload.get("event_type") or "kafka_event")

    async with db.async_session() as session:
        # ── Agent tracking (upsert) ──────────────────────────────────────
        matches = (await session.execute(select(Agent).where(Agent.hostname == hostname))).scalars().all()
        if matches:
            agent = matches[0]
            if len(matches) > 1:
                await session.execute(delete(Agent).where(Agent.id.in_([row.id for row in matches[1:]])))
            agent.id = agent_id or agent.id
            agent.hostname = hostname
            agent.os_type = agent.os_type or ("windows" if "win" in hostname.lower() else "linux")
            agent.status = "active"
            agent.ip_address = source_ip or agent.ip_address or "127.0.0.1"
            agent.last_checkin = event_timestamp
            agent.events_processed = (agent.events_processed or 0) + 1
        else:
            agent = Agent(
                id=agent_id,
                hostname=hostname,
                os_type="windows" if "win" in hostname.lower() else "linux",
                status="active",
                version="1.0.0",
                ip_address=source_ip,
                events_processed=1,
                last_checkin=event_timestamp,
            )
            session.add(agent)

        # ── Detection engine (in-memory — no raw Event rows) ────────────
        try:
            detection_event = {
                "id": str(payload.get("id") or os.urandom(8).hex()),
                "timestamp": event_timestamp,
                "source_ip": source_ip,
                "destination_ip": str(payload.get("destination_ip") or ""),
                "hostname": hostname,
                "agent_id": agent_id,
                "event_type": event_type,
                "event_data": payload.get("event_data") or payload,
                "status": "new",
            }
            await detection_engine.process_event(session, detection_event)
        except Exception as de_err:
            logger.exception("Detection engine processing failed: %s", de_err)

        await session.commit()

    logger.info("Processed Kafka telemetry (agent=%s, type=%s)", hostname, event_type)


async def consume_once() -> None:
    db = Database()
    await db.connect()

    # Start detection engine + redis so events from Kafka trigger alerts
    redis_service = RedisService()
    await redis_service.connect()
    detection_engine = DetectionEngine(db, redis_service)
    await detection_engine.start()
    logger.info("Detection engine started inside kafka_consumer")

    # Start the Kafka producer from app.main so alerts can be published
    # to the spyderxdr.alerts topic. Without this, any alert generated by
    # the detection engine will fail with "Real Kafka producer is unavailable".
    kafka_started = await _start_kafka_service_for_alerts()

    # Also start the ES-indexing consumer task so events are written to
    # Elasticsearch. The main backend's KafkaService._consume_real() (which
    # does this) only runs inside the uvicorn lifespan — when running
    # standalone, kafka_consumer.py would process events for detection but
    # never persist them to ES, leaving the SIEM page with stale data.
    es_consumer_started = await _start_es_index_consumer()
    if es_consumer_started:
        logger.info("✅ ES index consumer started — events will be written to Elasticsearch")

    consumer = AIOKafkaConsumer(
        TOPIC,
        bootstrap_servers=BROKER,
        auto_offset_reset="latest",
        enable_auto_commit=True,
        group_id="spyderxdr-consumer",
    )

    try:
        await consumer.start()
        logger.info("Starting async Kafka consumer on %s topic=%s", BROKER, TOPIC)

        async for msg in consumer:
            try:
                if not msg.value:
                    continue

                payload = json.loads(msg.value.decode("utf-8"))
                if not isinstance(payload, dict):
                    continue

                await _process_kafka_message(db, payload, detection_engine)
            except Exception as exc:
                logger.exception("Kafka consumer write failed: %s", exc)
    finally:
        await consumer.stop()
        if kafka_started:
            await _stop_kafka_service()
        await detection_engine.stop()
        await redis_service.disconnect()
        await db.disconnect()


async def _start_kafka_service_for_alerts() -> bool:
    """
    Start the KafkaService from app.main so the detection engine can produce
    alerts to the ``spyderxdr.alerts`` topic.

    The standalone ``kafka_consumer.py`` doesn't run the FastAPI lifespan, so
    ``app.main.kafka_service`` is declared at module level but never started.
    Without this, any alert triggered by the detection engine fails with
    "Real Kafka producer is unavailable".
    """
    try:
        from app.main import kafka_service as main_kafka
        await main_kafka.start()
        logger.info("✅ KafkaService started for alert publishing")
        return True
    except Exception as e:
        logger.warning("⚠️ Could not start KafkaService for alerts: %s", e)
        return False


async def _start_es_index_consumer() -> bool:
    """
    Start the Elasticsearch-indexing Kafka consumer task.

    The main backend runs this via ``KafkaService.start_consuming()`` inside
    the uvicorn lifespan. When ``kafka_consumer.py`` runs standalone, we need
    to start it explicitly so events are persisted to ES for the SIEM page.

    IMPORTANT: ``app.main.elastic_service.start()`` MUST be called first —
    the module-level ``ElasticSearchService()`` is created without calling
    ``start()``, so ``_client`` is ``None``. Without this, the ES consumer
    silently drops every event (``bulk_index`` returns 0 on ``None`` client).
    """
    try:
        from app.main import elastic_service as main_es
        from app.main import kafka_service as main_kafka
        from app.kafka.kafka_service import TOPIC_TELEMETRY

        # Start the Elasticsearch client so the consumer can bulk-index
        await main_es.start()
        logger.info("✅ Elasticsearch client started for ES index consumer")

        await main_kafka.start_consuming(topics=[TOPIC_TELEMETRY])
        return True
    except Exception as e:
        logger.warning("⚠️ Could not start ES index consumer: %s", e)
        return False


async def _stop_kafka_service() -> None:
    try:
        from app.main import kafka_service as main_kafka
        await main_kafka.stop()
    except Exception:
        pass


def main() -> None:
    asyncio.run(consume_once())


if __name__ == "__main__":
    # When connecting to Docker-based Redis, ensure REDIS_URL includes the password.
    # Docker Redis runs with: --requirepass xdr_redis_pass
    # Set: REDIS_URL=redis://:xdr_redis_pass@localhost:6379
    if "REDIS_URL" not in os.environ:
        logger.info("REDIS_URL not set — trying Docker Redis with default password")
        os.environ.setdefault("REDIS_URL", "redis://:xdr_redis_pass@localhost:6379")
    main()
